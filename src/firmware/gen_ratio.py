"""Generate ratio.c: CTRL 3 knob position (0..127) -> speed ratio, stored as u8 x with
ratio = (x + 128) / 256 (0.5 .. 1.496). 0..2 = OFF (1.0), 3 = -12 semitones, 62..65 = exactly 1.0,
124 = +7 semitones, 125..127 = PTN (handled in code; table entry 1.0)."""
def cents(v):
    if v <= 2: return 0                              # fully left: OFF (normal speed), like CTRL 1
    if v <= 61: return -1200 + (v - 3) * 1200 / 59
    if v <= 65: return 0
    if v <= 124: return (v - 65) * 700 / 59
    return 0                                         # PTN zone: ratio computed from the pattern tempo
tab = [min(255, round(256 * 2 ** (cents(v) / 1200)) - 128) for v in range(128)]
assert all(tab[v] == 128 for v in (0, 1, 2, 62, 63, 64, 65)) and tab[3] == 0 and tab[124] == 255 and tab[125:] == [128] * 3
assert all(b >= a for a, b in zip(tab[3:125], tab[4:125]))
open('ratio.c', 'w').write('/* generated by gen_ratio.py: ratio = (x + 128) / 256 */\n'
    'const unsigned char vari_ratio_u8[128] __attribute__((section(".rodata.wsp"))) = {\n' +
    ',\n'.join(', '.join(str(x) for x in tab[i:i + 16]) for i in range(0, 128, 16)) + '};\n')
