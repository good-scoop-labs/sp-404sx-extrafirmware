#!/usr/bin/env python3
"""Write the patch data used by both patchers (patch.py and the web page) from a release build.

The data holds only the bytes this project changes, as runs in the *unpacked* program image, plus the
hashes of the official input and of the expected output. Nothing from Roland's code is included: every
run covers changed bytes only. The patchers unpack the user's official file, write these runs and
re-pack it with the same minimal-change packer as the build (src/tools/sp404fw.py splice), so the result is
byte-identical to the build.

usage: python3 src/tools/make_patch_data.py official/sp404sx_up.bin out/sp404sx_up.bin
"""
import base64, hashlib, json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import sp404fw

NAME = 'SP-404SX/A EXTRAfirmware'
RELEASE = '2.00'
DATA = os.path.join(HERE, '..', '..', 'docs', 'extrafirmware-patch.js')


def runs_of(old, new):
    runs, i, n = [], 0, len(old)
    while i < n:
        if old[i] != new[i]:
            j = i
            while j < n and old[j] != new[j]:
                j += 1
            runs.append([i, base64.b64encode(new[i:j]).decode()])
            i = j
        else:
            i += 1
    return runs


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    official, built = (open(p, 'rb').read() for p in sys.argv[1:3])
    old_img, tag = sp404fw.unpack(official)
    new_img, tag2 = sp404fw.unpack(built)
    assert tag == tag2 and len(old_img) == len(new_img)
    runs = runs_of(old_img, new_img)
    # the data must reproduce the build exactly
    img = bytearray(old_img)
    for off, b64 in runs:
        b = base64.b64decode(b64)
        img[off:off + len(b)] = b
    out, _ = sp404fw.splice(official, bytes(img))
    assert out == built, 'patch data does not reproduce the build'
    h = lambda b: {'size': len(b), 'md5': hashlib.md5(b).hexdigest(), 'sha256': hashlib.sha256(b).hexdigest()}
    data = {
        'name': NAME, 'release': RELEASE,
        'input': dict(h(official), description='Roland SP-404SX System Update 1.07, sp404sx_up.bin'),
        'output': h(built),
        'image': {'size': len(old_img), 'changed_bytes': sum(len(base64.b64decode(r[1])) for r in runs)},
        'runs': runs,
    }
    js = ('/* ' + NAME + ' ' + RELEASE + ' patch data. Generated by src/tools/make_patch_data.py; do not edit.\n'
          '   Only the bytes this project adds or changes (runs in the unpacked program image); no Roland code. */\n'
          'var EXTRAFIRMWARE_PATCH = ' + json.dumps(data, separators=(',', ':')) + ';\n'
          'if (typeof module !== "undefined") module.exports = EXTRAFIRMWARE_PATCH;\n')
    open(DATA, 'w').write(js)
    print(f'wrote {os.path.relpath(DATA)}: {len(runs)} runs, {data["image"]["changed_bytes"]} bytes, '
          f'output sha256 {data["output"]["sha256"]}')


if __name__ == '__main__':
    main()
